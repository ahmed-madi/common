def generate_translations():
    
    for key, value in translations.items():
        # Check if translation already exists
        existing = frappe.db.get_value(
            "Translation",
            {"language": "ar", "source_text": key},
            ["name", "translated_text"],
            as_dict=True
        )
        
        if existing:
            # Update existing translation if the value is different
            if existing.translated_text != value:
                frappe.db.set_value("Translation", existing.name, "translated_text", value)
                print(f"Updated: {key} -> {value}")
        else:
            # Create new translation
            d = frappe.new_doc("Translation")
            d.update({
                "language": "ar",
                "source_text": key,
                "translated_text": value,
            })
            d.save()
            print(f"Created: {key} -> {value}")
    
    frappe.db.commit()

